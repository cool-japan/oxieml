//! Gröbner bases over ℚ via Buchberger's algorithm.
//!
//! Given generators `f₁, …, f_m` of an ideal `I = ⟨f₁, …, f_m⟩ ⊆ ℚ[x₀, …, x_{n−1}]`
//! and a [`MonOrder`], [`groebner_basis`] returns the **unique reduced Gröbner
//! basis** of `I` under that order.
//!
//! # What a Gröbner basis is
//!
//! `G ⊆ I` is a Gröbner basis of `I` when
//!
//! ```text
//! ⟨ LT(g) : g ∈ G ⟩  =  ⟨ LT(f) : f ∈ I ⟩
//! ```
//!
//! i.e. the leading terms of `G` already generate the leading-term ideal of the
//! whole of `I`. The point of that condition is [`MultiPoly::reduce`]: dividing
//! any `f` by a Gröbner basis yields a remainder that is a **canonical normal
//! form** — independent of the order of the divisors, and zero *iff* `f ∈ I`.
//! Ideal membership, which is undecidable-looking in general, becomes a division.
//!
//! `G` is **reduced** when additionally every `g ∈ G` is monic and no monomial of
//! `g` is divisible by `LM(h)` for any other `h ∈ G`. For a fixed ideal and a
//! fixed monomial order the reduced Gröbner basis is **unique**, which is what
//! makes it a genuine canonical form for the ideal itself.
//!
//! # Buchberger's algorithm
//!
//! **Buchberger's criterion**: `G` is a Gröbner basis iff for every pair
//! `f, g ∈ G` the S-polynomial `S(f, g)` (see [`MultiPoly::s_polynomial`])
//! reduces to `0` modulo `G`. The algorithm is the obvious fixed-point iteration
//! on that criterion: take a pair whose S-polynomial has a nonzero remainder `r`,
//! adjoin `r` to `G`, repeat.
//!
//! ## Termination
//!
//! Whenever `r ≠ 0` is adjoined, `LM(r)` is — by definition of a remainder — not
//! divisible by `LM(g)` for any `g` already in `G`. So `LM(r) ∉ ⟨LT(G)⟩`, and the
//! monomial ideal `⟨LT(G)⟩` therefore grows **strictly** with every adjunction.
//! `ℚ[x₀, …, x_{n−1}]` is Noetherian (Hilbert's basis theorem; for monomial
//! ideals this is Dickson's lemma), so a strictly ascending chain of ideals must
//! be finite. Hence only finitely many elements are ever adjoined, the pair set
//! eventually drains, and the loop halts.
//!
//! ## Complexity — and why the caps in [`GroebnerOpts`] exist
//!
//! Termination says nothing about *cost*. The degrees occurring in a Gröbner
//! basis are **doubly exponential** in the number of variables in the worst case:
//! Mayr–Meyer (1982) exhibit ideals forcing degree `2^(2^Ω(n))`, and Dubé (1990)
//! proves the matching upper bound `2·((d²/2) + d)^(2^(n−1))` for generators of
//! degree `d`. Ideal membership is EXPSPACE-complete. Coefficients blow up badly
//! too, which is why this module is built on arbitrary-precision [`Coeff`]s —
//! machine integers would silently overflow long before the degrees did.
//!
//! Consequently every entry point takes a [`GroebnerOpts`] carrying hard caps on
//! pairs, basis size, degree and total rewriting steps. **When a cap is hit the
//! computation returns [`GroebnerError`] — it never returns a partial basis and
//! calls it a Gröbner basis.** A truncated Buchberger run produces a set that
//! generates the right ideal but has the wrong leading-term ideal, so normal
//! forms computed against it would be silently wrong; refusing to answer is the
//! only honest option.
//!
//! ## Pruning: both Buchberger criteria
//!
//! A naive run reduces `|G|²/2` S-polynomials, the overwhelming majority of which
//! reduce to zero and contribute nothing. Both classical criteria are implemented
//! (Cox–Little–O'Shea, Ch. 2 §10, Theorem 11):
//!
//! * **First / product / coprime criterion.** If `LM(f)` and `LM(g)` are
//!   coprime — `lcm(LM(f), LM(g)) = LM(f)·LM(g)` — then `S(f, g)` reduces to `0`
//!   modulo `{f, g}` automatically, so the pair can be discarded untested. This
//!   is what makes `⟨x², y³⟩` cost *zero* reductions: it is already a Gröbner
//!   basis, and the algorithm can see that without computing anything.
//!
//! * **Second / chain criterion.** For a pair `(i, j)`, if there is a `k ∉ {i, j}`
//!   with `LM(f_k) | lcm(LM(f_i), LM(f_j))` and the pairs `(i, k)` and `(j, k)`
//!   have both already left the pair set, then the syzygy for `(i, j)` is
//!   generated by those two, `S(f_i, f_j)` is guaranteed to reduce to `0`, and
//!   the pair can be discarded.
//!
//! [`GroebnerStats`] reports how many pairs each criterion eliminated.

use std::collections::BTreeSet;

use super::monomial::{self, MonOrder, Monomial};
use super::multivariate::MultiPoly;
use super::{Coeff, PolyError};

/// Hard limits and the monomial order for a Buchberger run.
///
/// The defaults are sized for the small systems this crate actually solves
/// (a handful of variables, low degree). They are deliberately *finite*: see the
/// complexity discussion in the [module documentation](self).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GroebnerOpts {
    /// The monomial order.
    pub order: MonOrder,
    /// Maximum number of critical pairs removed from the pair set.
    pub max_pairs: usize,
    /// Maximum number of elements in the (un-minimalized) working basis.
    pub max_basis_size: usize,
    /// Maximum total degree permitted for a new basis element.
    pub max_total_degree: u64,
    /// Total budget of division-algorithm rewriting steps for the whole run.
    ///
    /// This is the wall-clock guard: it bounds the *entire* computation, not one
    /// reduction, so a run cannot escape it by doing many cheap reductions.
    pub max_reduction_steps: u64,
}

impl Default for GroebnerOpts {
    fn default() -> Self {
        Self {
            order: MonOrder::Lex,
            max_pairs: 50_000,
            max_basis_size: 500,
            max_total_degree: 64,
            max_reduction_steps: 5_000_000,
        }
    }
}

impl GroebnerOpts {
    /// Default options under the given monomial order.
    #[must_use]
    pub fn with_order(order: MonOrder) -> Self {
        Self {
            order,
            ..Self::default()
        }
    }
}

/// Instrumentation for a Buchberger run.
///
/// Chiefly useful for asserting that the pruning criteria actually fire — a
/// Gröbner engine whose criteria are silently mis-wired still returns correct
/// bases, just exponentially more slowly, so correctness tests alone cannot
/// detect the bug.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct GroebnerStats {
    /// Critical pairs ever inserted into the pair set.
    pub pairs_generated: usize,
    /// Critical pairs removed from the pair set (pruned or reduced).
    pub pairs_processed: usize,
    /// Pairs discarded by the **product (first) criterion**.
    pub product_criterion_pruned: usize,
    /// Pairs discarded by the **chain (second) criterion**.
    pub chain_criterion_pruned: usize,
    /// S-polynomials actually computed and reduced.
    pub s_polynomials_reduced: usize,
    /// S-polynomials whose remainder was zero (wasted work the criteria missed).
    pub zero_reductions: usize,
    /// Size of the working basis before minimalization.
    pub raw_basis_size: usize,
    /// Size of the returned reduced basis.
    pub reduced_basis_size: usize,
    /// Largest total degree of any element ever adjoined to the working basis.
    pub max_degree: u64,
}

/// Why a Gröbner basis computation could not be completed.
///
/// Every variant means "**no answer**", never "here is a partial answer". See the
/// [module documentation](self) for why a truncated Buchberger run is worse than
/// useless.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum GroebnerError {
    /// The critical-pair budget was exhausted.
    PairLimit {
        /// The configured [`GroebnerOpts::max_pairs`].
        limit: usize,
    },
    /// The working basis grew past [`GroebnerOpts::max_basis_size`].
    BasisSizeLimit {
        /// The configured limit.
        limit: usize,
    },
    /// A new basis element exceeded [`GroebnerOpts::max_total_degree`].
    DegreeLimit {
        /// The total degree that triggered the refusal.
        degree: u64,
        /// The configured limit.
        limit: u64,
    },
    /// The rewriting-step budget was exhausted mid-reduction.
    ReductionLimit {
        /// The configured [`GroebnerOpts::max_reduction_steps`].
        limit: u64,
    },
    /// The generators do not all live in the same polynomial ring.
    DimensionMismatch {
        /// The `num_vars` of the first generator.
        expected: usize,
        /// The `num_vars` of the offending generator.
        got: usize,
    },
    /// An underlying polynomial operation failed.
    Poly(PolyError),
}

impl std::fmt::Display for GroebnerError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::PairLimit { limit } => write!(
                f,
                "Buchberger exceeded the critical-pair limit ({limit}); no Gröbner basis computed"
            ),
            Self::BasisSizeLimit { limit } => write!(
                f,
                "Buchberger exceeded the basis-size limit ({limit}); no Gröbner basis computed"
            ),
            Self::DegreeLimit { degree, limit } => write!(
                f,
                "Buchberger produced a basis element of total degree {degree}, exceeding the limit ({limit}); no Gröbner basis computed"
            ),
            Self::ReductionLimit { limit } => write!(
                f,
                "Buchberger exceeded the reduction-step budget ({limit}); no Gröbner basis computed"
            ),
            Self::DimensionMismatch { expected, got } => {
                write!(f, "generator lives in {got} variables, expected {expected}")
            }
            Self::Poly(e) => write!(f, "polynomial error: {e}"),
        }
    }
}

impl std::error::Error for GroebnerError {}

impl From<PolyError> for GroebnerError {
    fn from(e: PolyError) -> Self {
        Self::Poly(e)
    }
}

/// The **reduced** Gröbner basis of `⟨gens⟩` under `opts.order`.
///
/// The result is canonical: for a fixed ideal and order it does not depend on the
/// generators given, their order, or anything else. It is sorted by leading
/// monomial, descending.
///
/// The empty ideal `⟨0⟩` yields an empty basis. The unit ideal yields `[1]`.
///
/// # Errors
///
/// [`GroebnerError`] when a cap in `opts` is hit or the generators are
/// inconsistent. Never returns a partial basis.
pub fn groebner_basis(
    gens: &[MultiPoly],
    opts: &GroebnerOpts,
) -> Result<Vec<MultiPoly>, GroebnerError> {
    Ok(groebner_basis_with_stats(gens, opts)?.0)
}

/// [`groebner_basis`], additionally returning the run's [`GroebnerStats`].
///
/// # Errors
///
/// Same as [`groebner_basis`].
pub fn groebner_basis_with_stats(
    gens: &[MultiPoly],
    opts: &GroebnerOpts,
) -> Result<(Vec<MultiPoly>, GroebnerStats), GroebnerError> {
    let mut stats = GroebnerStats::default();

    // Drop zeros; they generate nothing and would break `leading_term`.
    let mut working: Vec<MultiPoly> = Vec::new();
    let mut num_vars: Option<usize> = None;
    for g in gens {
        match num_vars {
            None => num_vars = Some(g.num_vars),
            Some(n) if n != g.num_vars => {
                return Err(GroebnerError::DimensionMismatch {
                    expected: n,
                    got: g.num_vars,
                });
            }
            Some(_) => {}
        }
        if g.is_zero() {
            continue;
        }
        working.push(g.monic(opts.order)?);
    }

    if working.is_empty() {
        // The zero ideal: its reduced Gröbner basis is empty.
        return Ok((Vec::new(), stats));
    }

    let raw = buchberger(working, opts, &mut stats)?;
    stats.raw_basis_size = raw.len();

    let minimal = minimalize(raw, opts.order)?;
    let reduced = reduce_basis(minimal, opts.order)?;
    stats.reduced_basis_size = reduced.len();

    Ok((reduced, stats))
}

/// The improved Buchberger algorithm with both pruning criteria.
///
/// `working` must be non-empty, zero-free and monic. The returned basis is a
/// (generally non-minimal) Gröbner basis; [`minimalize`] and [`reduce_basis`]
/// turn it into the canonical one.
fn buchberger(
    mut working: Vec<MultiPoly>,
    opts: &GroebnerOpts,
    stats: &mut GroebnerStats,
) -> Result<Vec<MultiPoly>, GroebnerError> {
    let order = opts.order;

    // The critical-pair set `B`. Indices refer to positions in `working`, which
    // is append-only for the whole run, so an index never changes meaning.
    let mut pairs: BTreeSet<(usize, usize)> = BTreeSet::new();
    for j in 0..working.len() {
        for i in 0..j {
            pairs.insert((i, j));
            stats.pairs_generated += 1;
        }
    }

    let mut reduction_budget = opts.max_reduction_steps;

    while let Some((i, j)) = select_pair(&pairs, &working, order) {
        pairs.remove(&(i, j));
        stats.pairs_processed += 1;
        if stats.pairs_processed > opts.max_pairs {
            return Err(GroebnerError::PairLimit {
                limit: opts.max_pairs,
            });
        }

        let lm_i = leading_monomial(&working[i], order)?;
        let lm_j = leading_monomial(&working[j], order)?;

        // ── Criterion 1: product / coprime criterion ──────────────────────────
        //
        // If LM(f_i) and LM(f_j) share no variable then S(f_i, f_j) reduces to 0
        // modulo {f_i, f_j} unconditionally, so the pair carries no information.
        if lm_i.is_coprime(&lm_j) {
            stats.product_criterion_pruned += 1;
            continue;
        }

        // ── Criterion 2: chain criterion ──────────────────────────────────────
        if chain_criterion(i, j, &lm_i, &lm_j, &working, &pairs, order) {
            stats.chain_criterion_pruned += 1;
            continue;
        }

        let s_poly = MultiPoly::s_polynomial(&working[i], &working[j], order)?;
        stats.s_polynomials_reduced += 1;

        let Some((_, remainder)) = s_poly.divide_bounded(&working, order, &mut reduction_budget)?
        else {
            return Err(GroebnerError::ReductionLimit {
                limit: opts.max_reduction_steps,
            });
        };

        if remainder.is_zero() {
            stats.zero_reductions += 1;
            continue;
        }

        let degree = remainder.total_degree();
        if degree > opts.max_total_degree {
            return Err(GroebnerError::DegreeLimit {
                degree,
                limit: opts.max_total_degree,
            });
        }
        stats.max_degree = stats.max_degree.max(degree);

        if working.len() + 1 > opts.max_basis_size {
            return Err(GroebnerError::BasisSizeLimit {
                limit: opts.max_basis_size,
            });
        }

        // LM(remainder) is divisible by no LM already present, so ⟨LT(working)⟩
        // strictly grows here — this is exactly the step the termination proof
        // (see the module docs) bounds via the ascending chain condition.
        working.push(remainder.monic(order)?);
        let t = working.len() - 1;
        for i in 0..t {
            pairs.insert((i, t));
            stats.pairs_generated += 1;
        }
    }

    Ok(working)
}

/// Buchberger's **second (chain) criterion**.
///
/// Returns `true` when the pair `(i, j)` may be discarded: some other basis
/// element `f_k` has `LM(f_k) | lcm(LM(f_i), LM(f_j))`, and both `(i, k)` and
/// `(j, k)` have already left the pair set.
///
/// Because a pair `(a, b)` is inserted the moment `max(a, b)` joins the basis,
/// "not in `pairs`" is equivalent to "already handled", which is the hypothesis
/// the criterion's syzygy argument needs: the syzygy for `(i, j)` is then an
/// `S`-combination of two syzygies already known to reduce to zero.
fn chain_criterion(
    i: usize,
    j: usize,
    lm_i: &Monomial,
    lm_j: &Monomial,
    working: &[MultiPoly],
    pairs: &BTreeSet<(usize, usize)>,
    order: MonOrder,
) -> bool {
    let lcm_ij = lm_i.lcm(lm_j);
    for (k, f_k) in working.iter().enumerate() {
        if k == i || k == j {
            continue;
        }
        let Some(lm_k) = f_k.leading_exponents(order) else {
            continue;
        };
        if !monomial::divides(lm_k, lcm_ij.exponents()) {
            continue;
        }
        let ik = if i < k { (i, k) } else { (k, i) };
        let jk = if j < k { (j, k) } else { (k, j) };
        if !pairs.contains(&ik) && !pairs.contains(&jk) {
            return true;
        }
    }
    false
}

/// Pick the next critical pair by the **normal selection strategy**: minimize the
/// total degree of `lcm(LM(f_i), LM(f_j))`, breaking ties by the monomial order
/// on that lcm and finally by index, so the choice is deterministic.
///
/// Selection affects only cost, never correctness — Buchberger's criterion has to
/// hold for *every* pair, and the algorithm drains the whole pair set regardless.
/// The normal strategy is nonetheless a large practical win because it keeps the
/// working degree low for as long as possible.
fn select_pair(
    pairs: &BTreeSet<(usize, usize)>,
    working: &[MultiPoly],
    order: MonOrder,
) -> Option<(usize, usize)> {
    let mut best_pair: Option<(usize, usize)> = None;
    let mut best_degree: u64 = 0;
    let mut best_lcm: Vec<u32> = Vec::new();

    for &(i, j) in pairs {
        let (Some(lm_i), Some(lm_j)) = (
            working[i].leading_exponents(order),
            working[j].leading_exponents(order),
        ) else {
            continue;
        };
        let lcm = monomial::lcm_exponents(lm_i, lm_j);
        let degree = monomial::total_degree(&lcm);

        let replace = match best_pair {
            None => true,
            Some(best) => {
                degree < best_degree
                    || (degree == best_degree
                        && order.cmp_exponents(&lcm, &best_lcm) == std::cmp::Ordering::Less)
                    || (degree == best_degree && lcm == best_lcm && (i, j) < best)
            }
        };
        if replace {
            best_degree = degree;
            best_lcm = lcm;
            best_pair = Some((i, j));
        }
    }

    best_pair
}

/// Leading monomial of a basis element, which is never the zero polynomial here.
fn leading_monomial(p: &MultiPoly, order: MonOrder) -> Result<Monomial, GroebnerError> {
    p.leading_monomial(order)
        .ok_or(GroebnerError::Poly(PolyError::DivByZero))
}

/// Strip redundant elements: drop every `g` whose leading monomial is divisible
/// by the leading monomial of a *kept* element.
///
/// Removing such a `g` leaves `⟨LT(G)⟩` unchanged, so the result is still a
/// Gröbner basis. Processing in ascending leading-monomial order means the
/// smallest leading monomials are kept, and exact duplicates collapse to one.
fn minimalize(basis: Vec<MultiPoly>, order: MonOrder) -> Result<Vec<MultiPoly>, GroebnerError> {
    let mut items: Vec<(Vec<u32>, MultiPoly)> = Vec::with_capacity(basis.len());
    for p in basis {
        if p.is_zero() {
            continue;
        }
        let lm = leading_monomial(&p, order)?;
        items.push((lm.0, p));
    }
    items.sort_by(|a, b| order.cmp_exponents(&a.0, &b.0));

    let mut kept: Vec<(Vec<u32>, MultiPoly)> = Vec::new();
    for (lm, p) in items {
        if kept.iter().any(|(k, _)| monomial::divides(k, &lm)) {
            continue;
        }
        kept.push((lm, p));
    }

    kept.into_iter()
        .map(|(_, p)| p.monic(order).map_err(GroebnerError::from))
        .collect()
}

/// Fully reduce a *minimal* Gröbner basis into the canonical **reduced** one.
///
/// Each `g_i` is replaced by its remainder modulo the other elements. In a
/// minimal basis no `LM(g_j)` divides `LM(g_i)`, so the leading term of `g_i`
/// survives untouched: the remainder is nonzero and has the same leading
/// monomial. Leading monomials therefore never change during this pass, which is
/// why a single sweep suffices — an element reduced early cannot be un-reduced by
/// a later one.
fn reduce_basis(basis: Vec<MultiPoly>, order: MonOrder) -> Result<Vec<MultiPoly>, GroebnerError> {
    let mut result = basis;
    for i in 0..result.len() {
        let others: Vec<MultiPoly> = result
            .iter()
            .enumerate()
            .filter(|(k, _)| *k != i)
            .map(|(_, p)| p.clone())
            .collect();
        if others.is_empty() {
            result[i] = result[i].monic(order)?;
            continue;
        }
        let reduced = result[i].reduce(&others, order)?;
        result[i] = reduced.monic(order)?;
    }

    // Canonical output order: leading monomial descending.
    result.sort_by(|a, b| {
        match (a.leading_exponents(order), b.leading_exponents(order)) {
            (Some(x), Some(y)) => order.cmp_exponents(y, x),
            // Unreachable: a reduced basis has no zero element.
            _ => std::cmp::Ordering::Equal,
        }
    });
    Ok(result)
}

/// Decide whether `f ∈ ⟨gens⟩`.
///
/// Computes a Gröbner basis `G` of the ideal and tests whether the normal form of
/// `f` modulo `G` is zero. This is correct precisely *because* `G` is a Gröbner
/// basis: for an arbitrary generating set the remainder depends on the divisor
/// order and can be nonzero even for a member.
///
/// # Errors
///
/// [`GroebnerError`] when the basis cannot be computed within `opts`, or when `f`
/// and the generators live in different rings.
pub fn ideal_member(
    f: &MultiPoly,
    gens: &[MultiPoly],
    opts: &GroebnerOpts,
) -> Result<bool, GroebnerError> {
    let basis = groebner_basis(gens, opts)?;
    if basis.is_empty() {
        // The zero ideal contains only 0.
        return Ok(f.is_zero());
    }
    if f.num_vars != basis[0].num_vars {
        return Err(GroebnerError::DimensionMismatch {
            expected: basis[0].num_vars,
            got: f.num_vars,
        });
    }
    Ok(f.reduce(&basis, opts.order)?.is_zero())
}

/// Return `true` when `basis` is `[1]`, i.e. the ideal is the whole ring and the
/// system `f₁ = … = f_m = 0` has **no** solutions at all (not even complex ones).
///
/// This is the Weak Nullstellensatz read off the reduced Gröbner basis: over an
/// algebraically closed field, `V(I) = ∅ ⟺ 1 ∈ I ⟺ the reduced basis is [1]`.
#[must_use]
pub fn is_unit_ideal(basis: &[MultiPoly]) -> bool {
    basis.len() == 1 && basis[0].total_degree() == 0 && !basis[0].is_zero()
}

/// Decide whether the ideal with reduced Gröbner basis `basis` is
/// **zero-dimensional** — that is, whether the system has only finitely many
/// solutions over the algebraic closure.
///
/// # The Finiteness Theorem
///
/// (Cox–Little–O'Shea, Ch. 5 §3, Theorem 6.) For an ideal `I` and *any* monomial
/// order with Gröbner basis `G`, the following are equivalent:
///
/// * `V(I)` is finite;
/// * for **each** variable `x_i`, some `g ∈ G` has `LM(g) = x_i^{m_i}` — a pure
///   power of that single variable.
///
/// The intuition: `LM(g) = x_i^{m_i}` means every monomial `x_i^k` with
/// `k ≥ m_i` is in the leading-term ideal, so the quotient ring
/// `ℚ[x]/I` is spanned by the finitely many monomials with `α_i < m_i` for all
/// `i`, and a finite-dimensional quotient forces finitely many points.
///
/// The unit ideal `[1]` is reported as **not** zero-dimensional here; callers
/// should test [`is_unit_ideal`] first, since an empty solution set is a
/// different outcome from a finite non-empty one.
#[must_use]
pub fn is_zero_dimensional(basis: &[MultiPoly], order: MonOrder, num_vars: usize) -> bool {
    (0..num_vars).all(|i| {
        basis.iter().any(|g| {
            g.leading_monomial(order)
                .and_then(|m| m.pure_power_var())
                .is_some_and(|v| v == i)
        })
    })
}

/// Convenience: build a [`MultiPoly`] from `(coefficient, exponents)` pairs.
///
/// # Errors
///
/// Infallible; the `Result` mirrors the rest of the polynomial API.
pub fn multipoly_from_terms(
    terms: &[(Coeff, Vec<u32>)],
    num_vars: usize,
) -> Result<MultiPoly, PolyError> {
    let mut p = MultiPoly::zero(num_vars);
    for (c, e) in terms {
        if e.len() != num_vars {
            return Err(PolyError::NotPolynomial);
        }
        let mut term = MultiPoly::zero(num_vars);
        term.terms.insert(e.clone(), c.clone());
        p = p.add(&term)?;
    }
    Ok(p)
}

