    /// `c · x^e` term helper.
    fn t(c: i64, e: &[u32]) -> (Coeff, Vec<u32>) {
        (coeff_from_i64(c), e.to_vec())
    }

    fn poly(terms: &[(Coeff, Vec<u32>)], n: usize) -> MultiPoly {
        multipoly_from_terms(terms, n).expect("well-formed test polynomial")
    }

    /// x² + y² − 1 in 2 variables.
    fn circle() -> MultiPoly {
        poly(&[t(1, &[2, 0]), t(1, &[0, 2]), t(-1, &[0, 0])], 2)
    }

    /// x − y in 2 variables.
    fn diagonal() -> MultiPoly {
        poly(&[t(1, &[1, 0]), t(-1, &[0, 1])], 2)
    }

    #[test]
    fn product_criterion_prunes_coprime_leading_terms() {
        // ⟨x², y³⟩ is *already* a Gröbner basis: the leading monomials x² and y³
        // are coprime, so the single critical pair is killed by the product
        // criterion and NOT ONE S-polynomial is ever reduced.
        let gens = vec![poly(&[t(1, &[2, 0])], 2), poly(&[t(1, &[0, 3])], 2)];

        for order in [MonOrder::Lex, MonOrder::GrLex, MonOrder::GrevLex] {
            let opts = GroebnerOpts::with_order(order);
            let (basis, stats) =
                groebner_basis_with_stats(&gens, &opts).expect("⟨x², y³⟩ is trivial");

            assert_eq!(
                stats.pairs_generated,
                1,
                "exactly one critical pair exists ({})",
                order.name()
            );
            assert_eq!(
                stats.product_criterion_pruned,
                1,
                "the product criterion must prune it ({})",
                order.name()
            );
            assert_eq!(
                stats.s_polynomials_reduced,
                0,
                "no S-polynomial may be computed ({})",
                order.name()
            );
            assert_eq!(stats.chain_criterion_pruned, 0);

            // And the basis is exactly the input, up to the order-dependent sort
            // (x² outranks y³ under lex, y³ outranks x² under the graded orders).
            assert_eq!(basis.len(), 2);
            let mut got = basis.clone();
            let mut want = vec![poly(&[t(1, &[2, 0])], 2), poly(&[t(1, &[0, 3])], 2)];
            got.sort_by(|a, b| a.terms.keys().cmp(b.terms.keys()));
            want.sort_by(|a, b| a.terms.keys().cmp(b.terms.keys()));
            assert_eq!(got, want, "basis under {}", order.name());
        }
    }

    #[test]
    fn product_criterion_is_load_bearing_not_incidental() {
        // Sanity check on the instrumentation itself: the zero in the previous
        // test must mean something. Here the very first pair has leading monomials
        // x² and x — emphatically NOT coprime — so the product criterion cannot
        // fire on it and an S-polynomial must genuinely be reduced.
        let opts = GroebnerOpts::with_order(MonOrder::Lex);
        let (_, stats) = groebner_basis_with_stats(&[circle(), diagonal()], &opts)
            .expect("circle ∩ diagonal is easy");
        assert!(
            stats.s_polynomials_reduced >= 1,
            "a non-coprime pair must actually be reduced: {stats:?}"
        );
    }

    #[test]
    fn chain_criterion_fires_on_a_three_element_basis() {
        // ⟨x²y − 1, xy² − x⟩ needs several elements; with three or more basis
        // members sharing lcm divisibility the chain criterion gets a chance.
        let f = poly(&[t(1, &[2, 1]), t(-1, &[0, 0])], 2);
        let g = poly(&[t(1, &[1, 2]), t(-1, &[1, 0])], 2);
        let opts = GroebnerOpts::with_order(MonOrder::GrLex);
        let (basis, stats) = groebner_basis_with_stats(&[f, g], &opts).expect("terminates");

        assert!(!basis.is_empty());
        // The criteria together must eliminate work; assert the chain criterion
        // is wired up and firing at least once on this input.
        assert!(
            stats.chain_criterion_pruned >= 1,
            "chain criterion never fired: {stats:?}"
        );
    }

    #[test]
    fn lex_groebner_basis_of_circle_and_diagonal() {
        // ⟨x² + y² − 1, x − y⟩ under lex (x > y) has reduced basis
        //   { x − y,  y² − 1/2 }
        // The eliminant y² − 1/2 is the whole point: it is the generator of the
        // first elimination ideal I ∩ ℚ[y].
        let opts = GroebnerOpts::with_order(MonOrder::Lex);
        let basis = groebner_basis(&[circle(), diagonal()], &opts).expect("terminates");

        let expected_diag = poly(&[t(1, &[1, 0]), t(-1, &[0, 1])], 2);
        let expected_elim = poly(
            &[
                (coeff_from_i64(1), vec![0, 2]),
                (
                    coeff_from_i64_ratio(-1, 2).expect("nonzero denominator"),
                    vec![0, 0],
                ),
            ],
            2,
        );

        assert_eq!(basis.len(), 2, "basis = {basis:?}");
        assert_eq!(basis[0], expected_diag, "leading element should be x − y");
        assert_eq!(basis[1], expected_elim, "eliminant should be y² − 1/2");
    }

    #[test]
    fn reduced_basis_is_canonical_across_generator_permutations() {
        // The reduced Gröbner basis depends only on the ideal and the order — not
        // on which generators were handed in, nor in what sequence.
        let opts = GroebnerOpts::with_order(MonOrder::Lex);
        let a = groebner_basis(&[circle(), diagonal()], &opts).expect("terminates");
        let b = groebner_basis(&[diagonal(), circle()], &opts).expect("terminates");
        assert_eq!(a, b);

        // Add a redundant generator that is already in the ideal: 2·(x − y).
        let redundant = diagonal().scale(&coeff_from_i64(2)).expect("infallible");
        let c = groebner_basis(&[circle(), diagonal(), redundant], &opts).expect("terminates");
        assert_eq!(a, c, "a redundant generator must not change the basis");
    }

    #[test]
    fn ideal_membership_xy_in_x_y_but_not_one() {
        // ⟨x, y⟩ — the maximal ideal at the origin.
        let gens = vec![poly(&[t(1, &[1, 0])], 2), poly(&[t(1, &[0, 1])], 2)];
        let opts = GroebnerOpts::default();

        // xy ∈ ⟨x, y⟩  (it is x·y, visibly a combination)
        let xy = poly(&[t(1, &[1, 1])], 2);
        assert!(ideal_member(&xy, &gens, &opts).expect("terminates"));

        // 1 ∉ ⟨x, y⟩  (every element vanishes at the origin; 1 does not)
        let one = poly(&[t(1, &[0, 0])], 2);
        assert!(!ideal_member(&one, &gens, &opts).expect("terminates"));

        // x² + 3y ∈ ⟨x, y⟩, but x² + 3y + 1 ∉ ⟨x, y⟩.
        let inside = poly(&[t(1, &[2, 0]), t(3, &[0, 1])], 2);
        let outside = poly(&[t(1, &[2, 0]), t(3, &[0, 1]), t(1, &[0, 0])], 2);
        assert!(ideal_member(&inside, &gens, &opts).expect("terminates"));
        assert!(!ideal_member(&outside, &gens, &opts).expect("terminates"));
    }

    #[test]
    fn ideal_membership_needs_a_groebner_basis_not_just_generators() {
        // The classic example (CLO Ch. 2 §6): f = xy² − x is in ⟨xy − 1, y² − 1⟩,
        // yet naive division by the generators *in the wrong order* leaves a
        // nonzero remainder. Going through the Gröbner basis must still say yes.
        let g1 = poly(&[t(1, &[1, 1]), t(-1, &[0, 0])], 2);
        let g2 = poly(&[t(1, &[0, 2]), t(-1, &[0, 0])], 2);
        let f = poly(&[t(1, &[1, 2]), t(-1, &[1, 0])], 2);

        let opts = GroebnerOpts::with_order(MonOrder::Lex);
        assert!(
            ideal_member(&f, &[g1.clone(), g2.clone()], &opts).expect("terminates"),
            "xy² − x = y·(xy − 1) + 1·(y² − 1)·0 + … is in the ideal"
        );
    }

    #[test]
    fn membership_of_every_generator_and_combination_is_stable() {
        // Property: every generator, and every polynomial combination of them,
        // must test as a member; a random-looking outsider must not.
        let gens = vec![circle(), diagonal()];
        let opts = GroebnerOpts::with_order(MonOrder::GrevLex);
        for g in &gens {
            assert!(ideal_member(g, &gens, &opts).expect("terminates"));
        }
        // (x + 2y)·(x² + y² − 1) + (3 − y)·(x − y) ∈ I
        let m1 = poly(&[t(1, &[1, 0]), t(2, &[0, 1])], 2);
        let m2 = poly(&[t(3, &[0, 0]), t(-1, &[0, 1])], 2);
        let combo = m1
            .mul(&circle())
            .expect("infallible")
            .add(&m2.mul(&diagonal()).expect("infallible"))
            .expect("infallible");
        assert!(ideal_member(&combo, &gens, &opts).expect("terminates"));

        // x alone is not in the ideal (the variety is two isolated points).
        let x = poly(&[t(1, &[1, 0])], 2);
        assert!(!ideal_member(&x, &gens, &opts).expect("terminates"));
    }

    #[test]
    fn unit_ideal_is_detected() {
        // ⟨x, x − 1⟩ = ⟨1⟩: no solutions anywhere.
        let gens = vec![
            poly(&[t(1, &[1, 0])], 2),
            poly(&[t(1, &[1, 0]), t(-1, &[0, 0])], 2),
        ];
        let opts = GroebnerOpts::default();
        let basis = groebner_basis(&gens, &opts).expect("terminates");
        assert!(is_unit_ideal(&basis), "basis = {basis:?}");
        assert_eq!(basis.len(), 1);
        assert_eq!(basis[0], poly(&[t(1, &[0, 0])], 2), "must be exactly 1");
    }

    #[test]
    fn zero_dimensionality_detection() {
        let opts = GroebnerOpts::with_order(MonOrder::Lex);

        // Two isolated points: zero-dimensional.
        let finite = groebner_basis(&[circle(), diagonal()], &opts).expect("terminates");
        assert!(is_zero_dimensional(&finite, MonOrder::Lex, 2));

        // The circle alone is a curve: infinitely many points, NOT zero-dim.
        // Its lex basis is {x² + y² − 1}, whose only leading monomial is x² —
        // there is no pure power of y, so the Finiteness Theorem says no.
        let curve = groebner_basis(&[circle()], &opts).expect("terminates");
        assert!(!is_zero_dimensional(&curve, MonOrder::Lex, 2));
    }

    #[test]
    fn zero_ideal_has_empty_basis() {
        let zero = MultiPoly::zero(2);
        let opts = GroebnerOpts::default();
        let basis = groebner_basis(std::slice::from_ref(&zero), &opts).expect("trivial");
        assert!(basis.is_empty());
        // Only 0 belongs to the zero ideal.
        assert!(ideal_member(&zero, std::slice::from_ref(&zero), &opts).expect("trivial"));
        let one = poly(&[t(1, &[0, 0])], 2);
        assert!(!ideal_member(&one, std::slice::from_ref(&zero), &opts).expect("trivial"));
    }

    #[test]
    fn caps_produce_an_honest_error_not_a_partial_basis() {
        // Force a degree cap so low that the eliminant y² − 1/2 cannot be formed,
        // and check we get a refusal rather than a truncated "basis".
        let opts = GroebnerOpts {
            order: MonOrder::Lex,
            max_total_degree: 1,
            ..GroebnerOpts::default()
        };
        let err = groebner_basis(&[circle(), diagonal()], &opts)
            .expect_err("degree cap 1 cannot hold a degree-2 eliminant");
        assert!(
            matches!(err, GroebnerError::DegreeLimit { limit: 1, .. }),
            "got {err:?}"
        );

        // A reduction-step budget of zero must also refuse rather than return [].
        let opts = GroebnerOpts {
            order: MonOrder::Lex,
            max_reduction_steps: 0,
            ..GroebnerOpts::default()
        };
        let err = groebner_basis(&[circle(), diagonal()], &opts).expect_err("no budget at all");
        assert!(
            matches!(err, GroebnerError::ReductionLimit { limit: 0 }),
            "got {err:?}"
        );

        // And a pair cap of zero.
        let opts = GroebnerOpts {
            order: MonOrder::Lex,
            max_pairs: 0,
            ..GroebnerOpts::default()
        };
        let err = groebner_basis(&[circle(), diagonal()], &opts).expect_err("no pairs allowed");
        assert!(
            matches!(err, GroebnerError::PairLimit { limit: 0 }),
            "got {err:?}"
        );
    }

    #[test]
    fn every_generator_reduces_to_zero_modulo_its_own_basis() {
        // The defining sanity property of a Gröbner basis of ⟨F⟩: each f ∈ F must
        // have zero normal form. Checked across all three orders on a 3-variable
        // system (where lex and grevlex genuinely differ).
        //
        // Cyclic-3: x+y+z, xy+yz+zx, xyz−1.
        let f1 = poly(&[t(1, &[1, 0, 0]), t(1, &[0, 1, 0]), t(1, &[0, 0, 1])], 3);
        let f2 = poly(&[t(1, &[1, 1, 0]), t(1, &[0, 1, 1]), t(1, &[1, 0, 1])], 3);
        let f3 = poly(&[t(1, &[1, 1, 1]), t(-1, &[0, 0, 0])], 3);
        let gens = [f1, f2, f3];

        for order in [MonOrder::Lex, MonOrder::GrLex, MonOrder::GrevLex] {
            let opts = GroebnerOpts::with_order(order);
            let basis = groebner_basis(&gens, &opts)
                .unwrap_or_else(|e| panic!("cyclic-3 under {}: {e}", order.name()));
            assert!(!basis.is_empty());
            for f in &gens {
                let r = f.reduce(&basis, order).expect("division terminates");
                assert!(
                    r.is_zero(),
                    "generator did not reduce to 0 under {}: {r:?}",
                    order.name()
                );
            }
            // Buchberger's criterion itself: every S-pair of the basis must
            // reduce to zero. This is the direct certificate that `basis` really
            // *is* a Gröbner basis, independent of how it was produced.
            for i in 0..basis.len() {
                for j in (i + 1)..basis.len() {
                    let s = MultiPoly::s_polynomial(&basis[i], &basis[j], order)
                        .expect("basis elements are nonzero");
                    let r = s.reduce(&basis, order).expect("division terminates");
                    assert!(
                        r.is_zero(),
                        "S({i},{j}) did not reduce to 0 under {}",
                        order.name()
                    );
                }
            }
        }
    }

    #[test]
    fn division_reconstructs_the_dividend() {
        // f = Σ qᵢ·gᵢ + r must hold exactly.
        let f = poly(
            &[t(1, &[2, 1]), t(3, &[1, 1]), t(-2, &[0, 3]), t(5, &[0, 0])],
            2,
        );
        let divisors = vec![circle(), diagonal()];
        for order in [MonOrder::Lex, MonOrder::GrLex, MonOrder::GrevLex] {
            let (quotients, remainder) = f.divide(&divisors, order).expect("terminates");
            let mut acc = remainder.clone();
            for (q, g) in quotients.iter().zip(divisors.iter()) {
                acc = acc.add(&q.mul(g).expect("infallible")).expect("infallible");
            }
            assert_eq!(acc, f, "division identity failed under {}", order.name());
        }
    }

    #[test]
    fn s_polynomial_cancels_the_leading_terms() {
        let order = MonOrder::GrLex;
        let f = poly(&[t(1, &[2, 1]), t(1, &[0, 0])], 2); // x²y + 1
        let g = poly(&[t(3, &[1, 2]), t(-1, &[1, 0])], 2); // 3xy² − x
        let s = MultiPoly::s_polynomial(&f, &g, order).expect("both nonzero");

        // lcm(x²y, xy²) = x²y², so both scaled polys lead with x²y² and cancel.
        let lm_f = f.leading_monomial(order).expect("nonzero");
        let lm_g = g.leading_monomial(order).expect("nonzero");
        let lcm = lm_f.lcm(&lm_g);
        assert_eq!(lcm.exponents(), &[2, 2]);
        if let Some(lm_s) = s.leading_monomial(order) {
            assert_eq!(
                order.cmp_exponents(lm_s.exponents(), lcm.exponents()),
                std::cmp::Ordering::Less,
                "S-polynomial must drop strictly below the lcm"
            );
        }
    }
